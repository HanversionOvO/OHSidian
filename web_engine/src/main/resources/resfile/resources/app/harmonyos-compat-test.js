'use strict';

const fs = require('fs');
const os = require('os');
const path = require('path');

const PREFIX = '[HMOS-COMPAT]';

function errorInfo(error) {
	if (!error) return null;
	return {
		name: error.name,
		message: error.message,
		code: error.code,
		stack: error.stack
	};
}

function createReporter(dataPath, log) {
	const results = [];
	const resultPath = path.join(dataPath, 'harmonyos-compat-results.json');
	const emit = (name, status, detail) => {
		const entry = {
			time: new Date().toISOString(),
			name,
			status,
			detail: detail || {}
		};
		results.push(entry);
		const line = `${PREFIX} ${JSON.stringify(entry)}`;
		try {
			log(line);
		} catch (e) {
			console.log(line);
		}
		try {
			fs.writeFileSync(resultPath, JSON.stringify(results, null, 2), 'utf8');
		} catch (e) {
			console.error(`${PREFIX} failed to write results`, e);
		}
	};
	return { emit, resultPath };
}

function safePath(app, name) {
	try {
		return app.getPath(name);
	} catch (error) {
		return null;
	}
}

function ensureDir(dir) {
	fs.mkdirSync(dir, { recursive: true });
	return dir;
}

function testFsVault(vaultPath) {
	ensureDir(path.join(vaultPath, '.obsidian', 'plugins', 'hmos-compat-plugin'));
	const notePath = path.join(vaultPath, 'compat-note.md');
	const pluginManifestPath = path.join(vaultPath, '.obsidian', 'plugins', 'hmos-compat-plugin', 'manifest.json');
	const pluginMainPath = path.join(vaultPath, '.obsidian', 'plugins', 'hmos-compat-plugin', 'main.js');
	fs.writeFileSync(notePath, '# HarmonyOS compatibility vault\n\nThis file is generated by the port test harness.\n', 'utf8');
	fs.writeFileSync(pluginManifestPath, JSON.stringify({
		id: 'hmos-compat-plugin',
		name: 'HarmonyOS Compat Plugin',
		version: '0.0.1',
		minAppVersion: '1.0.0',
		description: 'Generated plugin fixture for HarmonyOS compatibility tests.',
		author: 'port-test',
		isDesktopOnly: false
	}, null, 2), 'utf8');
	fs.writeFileSync(pluginMainPath, [
		'module.exports = class HmosCompatPlugin {',
		'  async onload() {',
		'    console.log("[HMOS-COMPAT-PLUGIN] loaded");',
		'  }',
		'  onunload() {}',
		'};'
	].join('\n'), 'utf8');
	const readBack = fs.readFileSync(notePath, 'utf8');
	const renamePath = path.join(vaultPath, 'compat-renamed.md');
	fs.renameSync(notePath, renamePath);
	fs.renameSync(renamePath, notePath);
	return {
		vaultPath,
		notePath,
		pluginManifestPath,
		bytes: Buffer.byteLength(readBack)
	};
}

function configureObsidianVault(dataPath, vaultPath) {
	const configPath = path.join(dataPath, 'obsidian.json');
	let config = {};
	try {
		if (fs.existsSync(configPath)) {
			config = JSON.parse(fs.readFileSync(configPath, 'utf8'));
		}
	} catch (error) {
		config = {};
	}
	config.vaults = config.vaults || {};
	config.vaults['hmos-compat'] = {
		path: vaultPath,
		ts: Date.now(),
		open: true
	};
	fs.writeFileSync(configPath, JSON.stringify(config, null, 2), 'utf8');
	return configPath;
}

function prepareVaultConfig({ app, dataPath, log }) {
	const reporter = createReporter(dataPath, log);
	const candidates = [];
	const documentsPath = safePath(app, 'documents');
	if (documentsPath) candidates.push(path.join(documentsPath, 'ObsidianHarmonyCompatVault'));
	candidates.push(path.join(dataPath, 'ObsidianHarmonyCompatVault'));

	for (const candidate of candidates) {
		try {
			const vaultInfo = testFsVault(candidate);
			const configPath = configureObsidianVault(dataPath, candidate);
			reporter.emit('vault.prepare', 'pass', { ...vaultInfo, configPath });
			return { reporter, vaultPath: candidate, configPath };
		} catch (error) {
			reporter.emit('vault.prepare.candidate', 'fail', { candidate, error: errorInfo(error) });
		}
	}

	reporter.emit('vault.prepare', 'fail', { reason: 'No writable vault candidate' });
	return { reporter, vaultPath: null, configPath: null };
}

function withTimeout(promise, ms, label) {
	let timer;
	const timeout = new Promise((_, reject) => {
		timer = setTimeout(() => reject(new Error(`${label} timed out after ${ms}ms`)), ms);
	});
	return Promise.race([promise, timeout]).finally(() => clearTimeout(timer));
}

function waitForWebContents(webContents, eventName, timeoutMs) {
	return withTimeout(new Promise((resolve, reject) => {
		const done = () => {
			cleanup();
			resolve();
		};
		const fail = (_event, code, desc) => {
			cleanup();
			reject(new Error(`${eventName} failed: ${code || ''} ${desc || ''}`));
		};
		const cleanup = () => {
			webContents.removeListener(eventName, done);
			webContents.removeListener('did-fail-load', fail);
		};
		webContents.once(eventName, done);
		webContents.once('did-fail-load', fail);
	}), timeoutMs, eventName);
}

async function testNativeAddons({ emit }) {
	for (const moduleName of ['btime', 'get-fonts']) {
		try {
			const mod = require(`./node_modules/${moduleName}`);
			let callResult = 'loaded';
			if (moduleName === 'get-fonts' && mod && typeof mod.getFonts === 'function') {
				const fonts = mod.getFonts();
				callResult = Array.isArray(fonts) ? `fonts:${fonts.length}` : typeof fonts;
			}
			emit(`native-addon.${moduleName}`, 'pass', { callResult });
		} catch (error) {
			emit(`native-addon.${moduleName}`, 'fail', { error: errorInfo(error) });
		}
	}
}

async function testPluginLikeRenderer({ app, electron, dataPath, emit }) {
	const { BrowserWindow } = electron;
	if (typeof BrowserWindow !== 'function') {
		emit('plugin-renderer.browser-window-api', 'fail', { reason: 'BrowserWindow is not a constructor' });
		return;
	}

	let win;
	try {
		win = new BrowserWindow({
			width: 640,
			height: 480,
			show: false,
			webPreferences: {
				nodeIntegration: true,
				contextIsolation: false
			}
		});
		const markerPath = path.join(dataPath, 'harmonyos-plugin-renderer-marker.txt').replace(/\\/g, '\\\\');
		const html = 'data:text/html;charset=utf-8,' + encodeURIComponent('<html><body>compat</body></html>');
		win.loadURL(html);
		await waitForWebContents(win.webContents, 'did-finish-load', 8000);
		const value = await withTimeout(win.webContents.executeJavaScript(`
			const fs = require('fs');
			fs.writeFileSync('${markerPath}', 'renderer-node-ok', 'utf8');
			({ requireType: typeof require, fsExists: fs.existsSync('${markerPath}') });
		`), 8000, 'renderer executeJavaScript');
		emit('plugin-renderer.node-integration', value && value.fsExists ? 'pass' : 'fail', value);
	} catch (error) {
		emit('plugin-renderer.node-integration', 'fail', { error: errorInfo(error) });
	} finally {
		try {
			if (win && !win.isDestroyed()) win.close();
		} catch (error) {
			emit('plugin-renderer.cleanup', 'fail', { error: errorInfo(error) });
		}
	}
}

async function testMultiWindow({ electron, emit }) {
	const { BrowserWindow } = electron;
	if (typeof BrowserWindow !== 'function') {
		emit('multi-window.api', 'fail', { reason: 'BrowserWindow is not a constructor' });
		return;
	}

	const windows = [];
	try {
		for (let i = 0; i < 2; i++) {
			const win = new BrowserWindow({ width: 420, height: 300, show: false });
			windows.push(win);
			win.loadURL('data:text/html;charset=utf-8,' + encodeURIComponent(`<html><title>compat-${i}</title><body>${i}</body></html>`));
			await waitForWebContents(win.webContents, 'did-finish-load', 8000);
		}
		emit('multi-window.create-two', 'pass', {
			count: windows.length,
			ids: windows.map((win) => win.id)
		});
	} catch (error) {
		emit('multi-window.create-two', 'fail', { error: errorInfo(error), created: windows.length });
	} finally {
		for (const win of windows) {
			try {
				if (!win.isDestroyed()) win.close();
			} catch (error) {
				emit('multi-window.cleanup', 'fail', { error: errorInfo(error) });
			}
		}
	}
}

async function testTray({ electron, appPath, emit }) {
	const { Tray, Menu, nativeImage } = electron;
	if (typeof Tray !== 'function') {
		emit('tray.api', 'fail', { reason: 'Tray is not a constructor' });
		return;
	}

	let tray;
	try {
		const iconPath = path.join(appPath, 'icon.png');
		const image = nativeImage && nativeImage.createFromPath ? nativeImage.createFromPath(iconPath) : iconPath;
		tray = new Tray(image);
		tray.setToolTip('Obsidian HarmonyOS compat');
		if (Menu && typeof Menu.buildFromTemplate === 'function') {
			tray.setContextMenu(Menu.buildFromTemplate([{ label: 'Compat', enabled: false }]));
		}
		emit('tray.create-and-menu', 'pass', { iconPath });
	} catch (error) {
		emit('tray.create-and-menu', 'fail', { error: errorInfo(error) });
	} finally {
		try {
			if (tray && typeof tray.destroy === 'function') tray.destroy();
		} catch (error) {
			emit('tray.cleanup', 'fail', { error: errorInfo(error) });
		}
	}
}

async function testPathsAndPermissions({ app, vaultPath, emit }) {
	const paths = {};
	for (const key of ['userData', 'home', 'documents', 'desktop', 'downloads', 'temp']) {
		paths[key] = safePath(app, key);
	}
	emit('paths.resolve', 'pass', paths);

	for (const key of ['documents', 'desktop', 'downloads']) {
		if (!paths[key]) {
			emit(`permission.write.${key}`, 'skip', { reason: 'app.getPath returned empty' });
			continue;
		}
		try {
			const filePath = path.join(paths[key], `obsidian-hmos-${key}.txt`);
			fs.writeFileSync(filePath, `${key} write ${new Date().toISOString()}`, 'utf8');
			const ok = fs.readFileSync(filePath, 'utf8').includes(key);
			emit(`permission.write.${key}`, ok ? 'pass' : 'fail', { filePath });
		} catch (error) {
			emit(`permission.write.${key}`, 'fail', { path: paths[key], error: errorInfo(error) });
		}
	}

	if (vaultPath) {
		try {
			const watchTarget = path.join(vaultPath, 'watch-target.md');
			fs.writeFileSync(watchTarget, 'watch-start', 'utf8');
			let observed = false;
			const watcher = fs.watch(vaultPath, () => {
				observed = true;
			});
			fs.writeFileSync(watchTarget, 'watch-change', 'utf8');
			await new Promise((resolve) => setTimeout(resolve, 500));
			watcher.close();
			emit('vault.fs-watch', observed ? 'pass' : 'fail', { vaultPath });
		} catch (error) {
			emit('vault.fs-watch', 'fail', { vaultPath, error: errorInfo(error) });
		}
	}
}

async function run(options) {
	const { app, electron, appPath, dataPath, log, vaultPath } = options;
	const reporter = createReporter(dataPath, log);
	const emit = reporter.emit;
	emit('test.start', 'pass', {
		resultPath: reporter.resultPath,
		platform: process.platform,
		arch: process.arch,
		node: process.versions.node,
		electron: process.versions.electron,
		versions: process.versions
	});

	try {
		await app.whenReady();
	} catch (error) {
		emit('app.whenReady', 'fail', { error: errorInfo(error) });
		return;
	}

	await testPathsAndPermissions({ app, vaultPath, emit });
	await testNativeAddons({ emit });
	await testTray({ electron, appPath, emit });
	await testMultiWindow({ electron, emit });
	await testPluginLikeRenderer({ app, electron, dataPath, emit });

	emit('file-persist.external-vault', 'manual', {
		reason: 'HarmonyOS fileShare.persistPermission requires a URI returned by DocumentViewPicker; this cannot be granted headlessly through hdc.',
		adapter: 'web_engine/src/main/ets/adapter/PermissionManagerAdapter.ets'
	});
	emit('test.end', 'pass', { resultPath: reporter.resultPath });
}

